package com.p2petrovich.telegramnewsreader.utils

/**
 * Ёфикатор — восстанавливает букву «ё» в тексте перед синтезом речи.
 *
 * Зачем: в обычном русском тексте «ё» почти всегда пишут как «е», но TTS-движки
 * (в т.ч. Edge Neural) ставят ударение по написанию. Без «ё» слова вроде
 * «передохнём/передохнем», «слёз/слез», «нёбо/небо» читаются неверно.
 *
 * ВАЖНО про безопасность: в словарь включены ТОЛЬКО слова, где «е→ё» однозначно
 * при любом контексте. Контекстные омографы («все/всё», «ее/её», «небо/нёбо»,
 * «слез/слёз») сюда НЕ входят — их закрывает LLM-этап (см. buildDigestPrompt).
 *
 * Словарь основан на safe-части открытого проекта e2yo/eyo-kernel (MIT),
 * из которого отобраны частотные для новостных текстов слова и развёрнуты
 * в падежные формы. Полный словарь (~50k форм) намеренно НЕ подгружается,
 * чтобы не тратить память фонового TTS-сервиса.
 *
 * Использование:
 *   val safeText = Yoficator.yoficate(rawText)
 *
 * Расширение: при необходимости добавить слова через loadExtraDictionary(words).
 */
object Yoficator {

    // Токенизация по границам кириллических слов — сохраняем всё остальное как есть
    // (пунктуацию, цифры, пробелы, латиницу — TTS-провайдер сам их не трогает).
    private val WORD_PATTERN = Regex("[А-Яа-яЁё]+")

    // key: нижний регистр слова с «е» на месте «ё»
    // value: правильный вариант с «ё» (в нижнем регистре — регистр восстанавливаем отдельно)
    // by lazy: SAFE_WORDS объявлен ниже по файлу, обычный val на этапе инициализации
    // объекта ещё не увидел бы его значение (forward reference) — lazy откладывает
    // вычисление до первого реального обращения к dictionary.
    private val dictionary: MutableMap<String, String> by lazy {
        HashMap(SAFE_WORDS.associateBy { it.replace('ё', 'е') })
    }

    /**
     * Догружает дополнительные слова с «ё» вручную (например, доменные термины).
     * Каждый элемент — одно слово с буквой «ё». Уже существующие ключи не перетираются.
     *
     * Публичный API на будущее (например, для загрузки внешнего списка из assets) —
     * пока нигде не вызывается, отсюда предупреждение линтера "never used", это нормально.
     */
    @Suppress("unused")
    fun loadExtraDictionary(words: List<String>) {
        words.forEach { w ->
            val withYo = w.trim().lowercase()
            if (withYo.isNotEmpty() && withYo.contains('ё')) {
                dictionary.putIfAbsent(withYo.replace('ё', 'е'), withYo)
            }
        }
    }

    /**
     * Восстанавливает «ё» в [text] там, где это однозначно безопасно.
     * Регистр исходного слова (ВСЕ КАПС / Капитализация / строчные) сохраняется.
     */
    fun yoficate(text: String): String {
        if (text.isEmpty()) return text
        return WORD_PATTERN.replace(text) { match ->
            val word = match.value
            // Слова, уже содержащие «ё», не трогаем (ключи в словаре — по «е»).
            if (word.contains('ё') || word.contains('Ё')) return@replace word
            val replacement = dictionary[word.lowercase()] ?: return@replace word
            applyCase(word, replacement)
        }
    }

    private fun applyCase(original: String, lowerReplacement: String): String {
        return when {
            original == original.uppercase() && original.any { it.isLetter() } ->
                lowerReplacement.uppercase()
            original[0].isUpperCase() ->
                lowerReplacement.replaceFirstChar { it.uppercase() }
            else -> lowerReplacement
        }
    }

